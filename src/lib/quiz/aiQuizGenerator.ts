export function generateDynamicSizingQuestion(difficulty: string): DynamicQuizQuestion {
  const diffNorm = difficulty.toLowerCase();
  
  let rows: number;
  let card: number;
  
  if (diffNorm.includes('easy')) {
    const rowOptions = [8000, 16000, 32000, 64000, 80000];
    rows = rowOptions[Math.floor(Math.random() * rowOptions.length)];
    card = 1; // Single vector
    const bytes = rows / 8;
    const kb = (bytes / 1024).toFixed(1);
    
    const correctStr = `${bytes.toLocaleString()} Bytes (${kb} KB)`;
    const distractor1 = `${(rows).toLocaleString()} Bytes`;
    const distractor2 = `${(bytes / 2).toLocaleString()} Bytes`;
    const distractor3 = `${(bytes * 8).toLocaleString()} Bytes`;
    
    return {
      id: `dyn_size_${Date.now()}_${Math.floor(Math.random() * 10000)}`,
      question: `For a database table containing exactly ${rows.toLocaleString()} rows, how much storage is required for a single uncompressed bitmap index vector?`,
      options: [correctStr, distractor1, distractor2, distractor3],
      correctAnswerIndex: 0,
      explanation: `Each row in the table occupies exactly 1 bit. Total bits = ${rows.toLocaleString()}. In bytes: ${rows.toLocaleString()} / 8 = ${bytes.toLocaleString()} Bytes (${kb} KB).`,
      difficulty: 'Easy',
      source: 'Generated by AI • Dynamic Sizing'
    };
  } else if (diffNorm.includes('hard')) {
    const rowOptions = [2000000, 4000000, 8000000, 16000000, 24000000];
    rows = rowOptions[Math.floor(Math.random() * rowOptions.length)];
    const cardOptions = [6, 8, 12, 16, 20];
    card = cardOptions[Math.floor(Math.random() * cardOptions.length)];
    
    const bytesPerVector = rows / 8;
    const totalBytes = bytesPerVector * card;
    const totalMB = (totalBytes / (1024 * 1024)).toFixed(2);
    
    const correctStr = `${totalMB} MB (${totalBytes.toLocaleString()} Bytes)`;
    const distractor1 = `${(totalBytes / 8 / (1024 * 1024)).toFixed(2)} MB`;
    const distractor2 = `${(totalBytes * 4 / (1024 * 1024)).toFixed(2)} MB`;
    const distractor3 = `${((rows * card) / (1024 * 1024)).toFixed(2)} MB`;
    
    return {
      id: `dyn_size_${Date.now()}_${Math.floor(Math.random() * 10000)}`,
      question: `In an enterprise analytical data warehouse with ${rows.toLocaleString()} rows, an uncompressed Bitmap Index is created on a column with cardinality ${card}. What is the total memory footprint for this index?`,
      options: [correctStr, distractor1, distractor2, distractor3],
      correctAnswerIndex: 0,
      explanation: `Memory calculation: (${rows.toLocaleString()} rows / 8 bits per byte) * ${card} vectors = ${totalBytes.toLocaleString()} Bytes = ${totalMB} MB.`,
      difficulty: 'Hard',
      source: 'Generated by AI • Dynamic Sizing'
    };
  } else {
    // Medium
    const rowOptions = [100000, 200000, 500000, 800000];
    rows = rowOptions[Math.floor(Math.random() * rowOptions.length)];
    const cardOptions = [3, 4, 5, 8];
    card = cardOptions[Math.floor(Math.random() * cardOptions.length)];
    
    const bytesPerVector = rows / 8;
    const totalBytes = bytesPerVector * card;
    const totalKB = (totalBytes / 1024).toFixed(1);
    
    const correctStr = `${totalKB} KB (${totalBytes.toLocaleString()} Bytes)`;
    const distractor1 = `${(totalBytes / 8 / 1024).toFixed(1)} KB`;
    const distractor2 = `${(totalBytes * 2 / 1024).toFixed(1)} KB`;
    const distractor3 = `${(totalBytes / 4 / 1024).toFixed(1)} KB`;
    
    return {
      id: `dyn_size_${Date.now()}_${Math.floor(Math.random() * 10000)}`,
      question: `If a table holds ${rows.toLocaleString()} rows and column "AccountType" has ${card} distinct values, what is the combined storage size of all ${card} bitmap vectors?`,
      options: [correctStr, distractor1, distractor2, distractor3],
      correctAnswerIndex: 0,
      explanation: `Each vector is ${rows.toLocaleString()} bits = ${(rows / 8).toLocaleString()} bytes. For ${card} distinct values, total size is ${card} * ${(rows / 8).toLocaleString()} = ${totalBytes.toLocaleString()} bytes = ${totalKB} KB.`,
      difficulty: 'Medium',
      source: 'Generated by AI • Dynamic Sizing'
    };
  }
}

export function generateDynamicBitwiseQuestion(difficulty: string): DynamicQuizQuestion {
  const len = 8;
  const vecA: number[] = [];
  const vecB: number[] = [];
  
  for (let i = 0; i < len; i++) {
    vecA.push(Math.random() > 0.45 ? 1 : 0);
    vecB.push(Math.random() > 0.45 ? 1 : 0);
  }
  
  const ops = ['AND', 'OR', 'XOR'];
  const op = ops[Math.floor(Math.random() * ops.length)];
  
  const resBits: number[] = [];
  for (let i = 0; i < len; i++) {
    if (op === 'AND') resBits.push(vecA[i] & vecB[i]);
    else if (op === 'OR') resBits.push(vecA[i] | vecB[i]);
    else resBits.push(vecA[i] ^ vecB[i]);
  }
  
  const strA = vecA.join('');
  const strB = vecB.join('');
  const strRes = resBits.join('');
  const popcount = resBits.filter(b => b === 1).length;
  
  // Make 3 distinct distractors
  const distractors: string[] = [];
  
  // Distractor 1: inverted result
  const inv = resBits.map(b => (b === 1 ? 0 : 1)).join('');
  if (inv !== strRes) distractors.push(inv);
  
  // Distractor 2: alternate operator
  const altOp = op === 'AND' ? 'OR' : 'AND';
  const altBits = vecA.map((b, i) => (altOp === 'AND' ? b & vecB[i] : b | vecB[i])).join('');
  if (altBits !== strRes && !distractors.includes(altBits)) distractors.push(altBits);
  
  // Fill remaining distractors
  while (distractors.length < 3) {
    const fake = Array.from({ length: len }, () => (Math.random() > 0.5 ? 1 : 0)).join('');
    if (fake !== strRes && !distractors.includes(fake)) {
      distractors.push(fake);
    }
  }

  const diffTag = difficulty.toLowerCase().includes('easy') ? 'Easy' : (difficulty.toLowerCase().includes('hard') ? 'Hard' : 'Medium');

  return {
    id: `dyn_bit_${Date.now()}_${Math.floor(Math.random() * 10000)}`,
    question: `Given two 8-row bitmap vectors:\nVector A = [${strA}]\nVector B = [${strB}]\nWhat is the resulting bit vector when evaluating the condition "A ${op} B"?`,
    options: [
      `[${strRes}] (matching ${popcount} rows)`,
      `[${distractors[0]}] (matching ${distractors[0].split('1').length - 1} rows)`,
      `[${distractors[1]}] (matching ${distractors[1].split('1').length - 1} rows)`,
      `[${distractors[2]}] (matching ${distractors[2].split('1').length - 1} rows)`
    ],
    correctAnswerIndex: 0,
    explanation: `Evaluating [${strA}] ${op} [${strB}] bit-by-bit produces [${strRes}]. There are ${popcount} set bits corresponding to the matching rows.`,
    difficulty: diffTag,
    source: `Generated by AI • Dynamic Boolean Logic`
  };
}

export function generateDynamicBreakEvenQuestion(difficulty: string): DynamicQuizQuestion {
  const buildTimes = [400, 600, 800, 1200, 1500, 2000];
  const scanTimes = [40, 50, 60, 80, 100, 120];
  const bitmapTimes = [2, 3, 4, 5, 6, 8];
  
  const buildTime = buildTimes[Math.floor(Math.random() * buildTimes.length)];
  const scanTime = scanTimes[Math.floor(Math.random() * scanTimes.length)];
  const bitmapTime = bitmapTimes[Math.floor(Math.random() * bitmapTimes.length)];
  
  const savingsPerQuery = scanTime - bitmapTime;
  const breakEven = Math.ceil(buildTime / savingsPerQuery);
  
  const correctStr = `${breakEven} queries`;
  const distractor1 = `${Math.ceil(buildTime / scanTime)} queries`;
  const distractor2 = `${breakEven + 5} queries`;
  const distractor3 = `${Math.max(1, breakEven - 4)} queries`;
  
  const diffTag = difficulty.toLowerCase().includes('easy') ? 'Easy' : (difficulty.toLowerCase().includes('hard') ? 'Hard' : 'Medium');

  return {
    id: `dyn_be_${Date.now()}_${Math.floor(Math.random() * 10000)}`,
    question: `A benchmark reveals: Index Build Time = ${buildTime} ms, Table Scan Query Time = ${scanTime} ms, and Bitmap Index Query Time = ${bitmapTime} ms. How many repeated queries must be executed to reach the break-even point?`,
    options: [correctStr, distractor1, distractor2, distractor3],
    correctAnswerIndex: 0,
    explanation: `Break-even formula: ceil(BuildTime / (TableScanTime - BitmapQueryTime)) = ceil(${buildTime} / (${scanTime} - ${bitmapTime})) = ceil(${buildTime} / ${savingsPerQuery}) = ${breakEven} queries. After ${breakEven} queries, the accumulated query time savings exceed the upfront index build cost.`,
    difficulty: diffTag,
    source: `Generated by AI • Dynamic Benchmark Analysis`
  };
}

/**
 * Shuffles the 4 options of a question and updates correctAnswerIndex accordingly.
 */
function shuffleOptions(question: DynamicQuizQuestion): Question {
  const originalCorrectText = question.options[question.correctAnswerIndex];
  const shuffled = [...question.options].sort(() => Math.random() - 0.5);
  const newCorrectIndex = shuffled.indexOf(originalCorrectText);

  return {
    id: question.id,
    question: question.question,
    options: shuffled,
    correctAnswerIndex: newCorrectIndex >= 0 ? newCorrectIndex : 0,
    explanation: question.explanation,
    source: question.source || 'Generated by AI'
  };
}

/**
 * Generates a dynamic, randomized set of AI questions for the requested difficulty and count.
 * Guaranteed to produce fresh, non-repeating questions by filtering out excludeIds and synthesizing
 * dynamic procedural questions on demand.
 */
export function generateDynamicAiQuiz(
  count: number, 
  difficulty: string = 'Medium',
  excludeIds: string[] = []
): Question[] {
  const normDiff = difficulty.toLowerCase();
  const excludeSet = new Set(excludeIds.map(id => String(id).trim()));
  
  // Filter pool by difficulty, or use full 60-question pool if 'All' or if count exceeds single tier
  let targetPool = AI_QUIZ_POOL.filter(q => {
    if (normDiff.includes('all') || normDiff.includes('comprehensive') || normDiff.includes('mixed')) return true;
    if (normDiff.includes('easy')) return q.difficulty === 'Easy';
    if (normDiff.includes('hard')) return q.difficulty === 'Hard';
    return q.difficulty === 'Medium';
  });

  // If requested count is greater than this single tier, expand to the full 60-question pool
  if (count > targetPool.length) {
    targetPool = [...AI_QUIZ_POOL];
  }

  // Filter out any questions already seen in this session
  let freshEligible = targetPool.filter(q => !excludeSet.has(q.id));
  if (freshEligible.length < count) {
    // If not enough unseen questions remain in this session, draw from full pool
    freshEligible = [...targetPool];
  }

  // Shuffle fresh candidates
  const shuffledPool = [...freshEligible].sort(() => Math.random() - 0.5);

  const selectedQuestions: DynamicQuizQuestion[] = [];

  // Take as many fresh pool questions as available up to count
  for (const q of shuffledPool) {
    if (selectedQuestions.length >= count) break;
    selectedQuestions.push(q);
  }

  // If pool alone does not satisfy count (or if many were excluded), synthesize procedural questions
  const proceduralGenerators = [
    () => generateDynamicSizingQuestion(difficulty),
    () => generateDynamicBitwiseQuestion(difficulty),
    () => generateDynamicBreakEvenQuestion(difficulty)
  ];

  let genIdx = 0;
  let attempts = 0;
  while (selectedQuestions.length < count && attempts < 20) {
    attempts++;
    const generator = proceduralGenerators[genIdx % proceduralGenerators.length];
    genIdx++;
    const dynamicQ = generator();
    if (!excludeSet.has(dynamicQ.id)) {
      selectedQuestions.push(dynamicQ);
      excludeSet.add(dynamicQ.id);
    }
  }

  // If still under count (extreme edge case where excludeIds covered everything), recycle target pool with shuffled options
  if (selectedQuestions.length < count) {
    const backupShuffled = [...targetPool].sort(() => Math.random() - 0.5);
    for (const q of backupShuffled) {
      if (selectedQuestions.length >= count) break;
      if (!selectedQuestions.some(existing => existing.id === q.id)) {
        selectedQuestions.push(q);
      }
    }
  }

  // Shuffle candidate options for every selected question
  return selectedQuestions.map(q => shuffleOptions(q));
}
