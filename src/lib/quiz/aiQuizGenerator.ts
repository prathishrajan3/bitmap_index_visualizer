/**
 * Shuffles the 4 options of a question and updates correctAnswerIndex accordingly.
 */
function shuffleOptions(question: DynamicQuizQuestion): Question {
  const originalCorrectText = question.options[question.correctAnswerIndex];
  const shuffled = [...question.options].sort(() => Math.random() - 0.5);
  const newCorrectIndex = shuffled.indexOf(originalCorrectText);

  return {
    id: question.id,
    question: question.question,
    options: shuffled,
    correctAnswerIndex: newCorrectIndex >= 0 ? newCorrectIndex : 0,
    explanation: question.explanation,
    source: question.source || 'Generated by AI'
  };
}

/**
 * Generates a dynamic, randomized set of AI questions for the requested difficulty and count.
 */
export function generateDynamicAiQuiz(count: number, difficulty: string = 'Medium'): Question[] {
  const normDiff = difficulty.toLowerCase();
  
  let primaryPool = AI_QUIZ_POOL.filter(q => {
    if (normDiff.includes('easy')) return q.difficulty === 'Easy';
    if (normDiff.includes('hard')) return q.difficulty === 'Hard';
    return q.difficulty === 'Medium';
  });

  // If pool has fewer questions than requested, supplement with other difficulties
  if (primaryPool.length < count) {
    const supplement = AI_QUIZ_POOL.filter(q => !primaryPool.includes(q));
    primaryPool = [...primaryPool, ...supplement];
  }

  // Shuffle candidate questions
  const shuffledQuestions = [...primaryPool].sort(() => Math.random() - 0.5);
  const selected = shuffledQuestions.slice(0, Math.min(count, shuffledQuestions.length));

  // Dynamically shuffle options for each selected question
  return selected.map(q => shuffleOptions(q));
}
